// tools/build_manifest.mjs
//
// Writes src/data/manifest.json: for every asset, its path, pack of origin,
// licence and source URL. Per 02_CLAUDE_CODE_BRIEF.md — do not skip this
// because CC0 does not require it; in six months nobody will remember what came
// from where.
//
//   node tools/build_manifest.mjs

import { readdir, stat, writeFile } from 'node:fs/promises';
import { join, relative, extname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const ASSETS = join(ROOT, 'assets');

// Directory prefix -> provenance. From 01_ASSET_MANIFEST.md's licence ledger.
const PROVENANCE = [
  ['assets/boats',          'Kenney Watercraft Kit',            'CC0', 'https://kenney.nl/assets/watercraft-kit'],
  ['assets/ui/sprites',     'Kenney UI Pack',                   'CC0', 'https://kenney.nl/assets/ui-pack'],
  ['assets/audio/sfx',      'Kenney Interface Sounds / UI Audio','CC0', 'https://kenney.nl/assets/interface-sounds'],
  ['assets/audio/ambience', 'Freesound (CC0-filtered only)',    'CC0', 'https://freesound.org'],
  ['assets/fish',           'Quaternius Animated Fish',         'CC0', 'https://opengameart.org/content/animated-fish'],
  ['assets/nature',         'Kenney Nature Kit / Quaternius Ultimate Nature Pack', 'CC0', 'https://kenney.nl/assets/nature-kit'],
  ['assets/textures',       'ambientCG',                        'CC0', 'https://ambientcg.com'],
];

const KIND = {
  '.glb': 'model', '.obj': 'model-source', '.fbx': 'model-source', '.gltf': 'model-source',
  '.png': 'texture', '.jpg': 'texture', '.jpeg': 'texture', '.webp': 'texture', '.bmp': 'texture',
  '.ogg': 'audio', '.mp3': 'audio', '.wav': 'audio',
  '.ttf': 'font', '.otf': 'font', '.woff2': 'font',
};

async function walk(dir, out = []) {
  let entries;
  try { entries = await readdir(dir, { withFileTypes: true }); } catch { return out; }
  for (const e of entries) {
    const p = join(dir, e.name);
    if (e.isDirectory()) await walk(p, out);
    else out.push(p);
  }
  return out;
}

const files = await walk(ASSETS);
const entries = [];
const counts = { model: 0, 'model-source': 0, texture: 0, audio: 0, font: 0, other: 0 };
let bytes = 0;

for (const f of files) {
  const rel = relative(ROOT, f).split('\\').join('/');
  const kind = KIND[extname(f).toLowerCase()] ?? 'other';
  const size = (await stat(f)).size;
  const prov = PROVENANCE.find(([p]) => rel.startsWith(p));
  counts[kind]++;
  bytes += size;
  entries.push({
    path: rel,
    kind,
    bytes: size,
    pack: prov ? prov[1] : 'UNKNOWN — record before shipping',
    licence: prov ? prov[2] : 'UNKNOWN',
    source: prov ? prov[3] : null,
  });
}

entries.sort((a, b) => a.path.localeCompare(b.path));

const manifest = {
  _generated: new Date().toISOString(),
  _note: 'Generated by tools/build_manifest.mjs. Every asset, its pack, licence and source URL. Keep current as things are added — see 01_ASSET_MANIFEST.md.',
  totals: { ...counts, files: entries.length, bytes, megabytes: +(bytes / 1048576).toFixed(2) },
  ledger: PROVENANCE.map(([prefix, pack, licence, source]) => ({ prefix, pack, licence, source, obligation: licence === 'CC0' ? 'none' : 'see 01_ASSET_MANIFEST.md' })),
  assets: entries,
};

await writeFile(join(ROOT, 'src/data/manifest.json'), JSON.stringify(manifest, null, 2) + '\n');

console.log('SINGING RIVER BASS — asset manifest');
console.log(`  models (.glb)   ${counts.model}`);
console.log(`  model sources   ${counts['model-source']}`);
console.log(`  textures        ${counts.texture}`);
console.log(`  audio clips     ${counts.audio}`);
console.log(`  fonts           ${counts.font}`);
console.log(`  other           ${counts.other}`);
console.log(`  ---------------`);
console.log(`  total           ${entries.length} files, ${(bytes / 1048576).toFixed(2)} MB on disk`);
const unknown = entries.filter((e) => e.licence === 'UNKNOWN');
if (unknown.length) {
  console.log(`\n  ${unknown.length} file(s) with UNKNOWN provenance — record before shipping:`);
  for (const u of unknown.slice(0, 20)) console.log('    ' + u.path);
}
console.log(`\nwrote src/data/manifest.json`);
